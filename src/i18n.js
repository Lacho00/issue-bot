export const DICTIONARIES = { es, en };

export function createT(lang = 'es') {
  const dict = DICTIONARIES[lang];
  if (!dict) throw new Error(`Idioma no soportado: ${lang}`);
  return function t(key, vars = {}) {
    if (!Object.hasOwn(dict, key)) throw new Error(`Clave de traducción desconocida: ${key}`);
    return dict[key].replace(/\{(\w+)\}/g, (m, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : m));
  };
}
